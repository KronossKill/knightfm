// Knight FM — Master UI/UX v2.0 THEME DELIVERABLES exporter.
// Single pipeline: globals.css → (T91 extraction) → THEME_TOKENS → this script
// → docs/ui/themes/{css,ts,json}/<theme>.*  (JSON + CSS + TypeScript parity).
//
// Run:  bun scripts/export-theme-deliverables.mjs
// Re-run after any token change in globals.css + theme-tokens.ts.

import { THEME_TOKENS, REQUIRED_TOKEN_NAMES, themeToCss } from "../src/lib/theme-tokens.ts";
import { THEMES } from "../src/lib/themes.ts";
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "docs", "ui", "themes");
mkdirSync(join(OUT, "css"), { recursive: true });
mkdirSync(join(OUT, "ts"), { recursive: true });
mkdirSync(join(OUT, "json"), { recursive: true });

const pascal = (id) => id.split("-").map((s) => s[0].toUpperCase() + s.slice(1)).join("");

// Token groups for the structured v2.0 JSON export.
const GROUPS = {
  surfaces: ["background", "card", "popover", "muted", "secondary", "accent", "sidebar", "sidebar-accent"],
  text: ["foreground", "card-foreground", "popover-foreground", "muted-foreground", "secondary-foreground", "accent-foreground", "sidebar-foreground"],
  brand: ["primary", "primary-foreground", "sidebar-primary", "sidebar-primary-foreground"],
  status: ["destructive", "danger"],
  feedback: ["ring", "input", "border", "sidebar-border"],
  charts: ["chart-1", "chart-2", "chart-3", "chart-4", "chart-5"],
};

const index = [];

for (const [id, th] of Object.entries(THEME_TOKENS)) {
  const meta = THEMES.find((t) => t.id === id);

  // ── CSS ──
  writeFileSync(join(OUT, "css", `${id}.css`), themeToCss(id) + "\n");

  // ── TypeScript ──
  const ts = `// Knight FM — theme tokens: ${th.label} (machine-generated by scripts/export-theme-deliverables.mjs — do not hand-edit).
// Source of truth: [data-theme="${id}"] in src/app/globals.css.
import type { ThemeTokenMap } from "@/lib/theme-tokens";

export const themeId = "${id}" as const;
export const mode = "${th.mode}" as const;
export const direction = ${JSON.stringify(th.direction)};

export const tokens: ThemeTokenMap = {
${Object.entries(th.tokens)
  .map(([k, v]) => `  "${k}": ${JSON.stringify(v)},`)
  .join("\n")}
};
export default tokens;
`;
  writeFileSync(join(OUT, "ts", `${id}.ts`), ts);

  // ── JSON (structured v2.0 export) ──
  const structured = {
    $schema: "https://knight.fm/schemas/theme-tokens-v2.json",
    meta: {
      id,
      label: th.label,
      mode: th.mode,
      direction: th.direction,
      nameKey: meta?.nameKey ?? `themes.${id}`,
      swatch: meta?.swatch ?? [],
      default: id === "knight-emerald",
    },
    groups: Object.fromEntries(
      Object.entries(GROUPS).map(([g, names]) => [
        g,
        Object.fromEntries(names.filter((n) => th.tokens[n]).map((n) => [n, th.tokens[n]])),
      ]),
    ),
    flat: th.tokens,
  };
  writeFileSync(join(OUT, "json", `${id}.json`), JSON.stringify(structured, null, 2) + "\n");
  index.push({ id, label: th.label, mode: th.mode });
}

// Parity guard: every theme must define exactly the same token names.
const ids = Object.keys(THEME_TOKENS);
for (const id of ids) {
  const names = Object.keys(THEME_TOKENS[id].tokens).sort();
  const required = [...REQUIRED_TOKEN_NAMES].sort();
  if (JSON.stringify(names) !== JSON.stringify(required)) {
    console.error(`PARITY FAIL: ${id} token set differs from the contract`);
    process.exit(1);
  }
}

// ── README index ──
const readme = `<!-- MACHINE-GENERATED by scripts/export-theme-deliverables.mjs — do not hand-edit. -->
# Knight FM — THEMES/ (Master UI/UX v2.0 deliverable)

5 temas · pipeline único: \`globals.css\` → \`src/lib/theme-tokens.ts\` → **este directorio**.
Regenerar tras cualquier cambio de tokens: \`bun scripts/export-theme-deliverables.mjs\`.
Verificación WCAG AA: \`bun scripts/verify-wcag-contrast.mjs\` → \`wcag-contrast.md\`.

| # | Tema | id | Modo | CSS | TS | JSON |
|---|------|----|------|-----|----|------|
${index
  .map(
    (t, i) =>
      `| ${i + 1} | ${t.label} | \`${t.id}\` | ${t.mode === "dark" ? "oscuro" : "claro"} | [css/${t.id}.css](css/${t.id}.css) | [ts/${t.id}.ts](ts/${t.id}.ts) | [json/${t.id}.json](json/${t.id}.json) |`,
  )
  .join("\n")}

## Contrato de tokens (paridad obligatoria en los 5 temas)

${[...REQUIRED_TOKEN_NAMES].sort().map((n) => `\`--${n}\``).join(" · ")}

## Grupos semánticos (JSON v2.0)

- **surfaces** — fondos: base, tarjeta, popover, muted, secondary, accent, sidebar.
- **text** — niveles de texto: primario, secundario (muted), sobre-acento, sidebar.
- **brand** — color de marca + color de texto sobre marca (botón primario).
- **status** — \`destructive\` (rojo de TEXTO, ≥4.5:1 sobre tarjetas) y \`danger\` (fondo de botón peligro, texto blanco ≥4.5:1).
- **feedback** — bordes, inputs y anillo de foco (≥3:1).
- **charts** — 5 series de gráficos distinguibles (≥3:1 sobre tarjeta).
`;
writeFileSync(join(OUT, "README.md"), readme);

console.log(`Exported ${ids.length} themes → docs/ui/themes/{css,ts,json}/ + README.md`);
for (const id of ids) console.log(`  · ${id}.css / ${id}.ts / ${id}.json`);
